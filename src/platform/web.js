/**
 * Browser build: every call goes to the Node backend (server/index.js).
 * Same interface as ./android.js.
 */

async function json(responsePromise) {
  const response = await responsePromise;
  const payload = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(payload.error || payload.message || `Request failed (HTTP ${response.status}).`);
  return payload;
}
const post = (path, body, method = 'POST') => fetch(path, {
  method,
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify(body),
});

export function createWebApi() {
  return {
    platform: 'web',
    features: { tvResearch: true },
    master: {
      /** Saved upload ({ name, uploadedAt, rows }) or null when none / backend unreachable. */
      async get() {
        try {
          const r = await fetch('/api/master-stock');
          return r.ok ? r.json() : null;
        } catch { return null; }
      },
      save: (name, rows) => json(post('/api/master-stock', { name, rows }, 'PUT')),
      async reset() {
        const r = await fetch('/api/master-stock', { method: 'DELETE' });
        if (!r.ok) throw new Error(`HTTP ${r.status}`);
      },
    },
    preopen: {
      /** Server-sent events: cached status once, then updates. Returns an unsubscribe function. */
      /** `onConnect` runs on every (re)connection, e.g. after the backend restarts. */
      subscribe(onUpdate, onError, onConnect) {
        let events;
        // Defer connection until after React StrictMode's setup/cleanup check.
        const startup = setTimeout(() => {
          events = new EventSource('/api/nse/preopen/events');
          events.onopen = () => onConnect?.();
          events.onmessage = (event) => {
            try { onUpdate(JSON.parse(event.data)); }
            catch { onError('Could not read the NSE update. Reload the page to reconnect.'); }
          };
          events.onerror = () => onError('NSE updates disconnected. Reconnecting to the backend…');
        }, 0);
        return () => { clearTimeout(startup); events?.close(); };
      },
      refresh: () => json(fetch('/api/nse/preopen/refresh', { method: 'POST' })),
      saveSchedule: (config) => json(post('/api/nse/schedule', config, 'PUT')),
    },
    priceBands: { get: () => json(fetch('/api/nse/price-bands')) },
    /** Context for the morning of trading day `date` (YYYY-MM-DD), default today. */
    context: { get: (date = null) => json(fetch(`/api/nse/context${date ? `?date=${encodeURIComponent(date)}` : ''}`)) },
    files: {
      /** Browser download of generated bytes; returns where it went. */
      async save(name, bytes, type = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet') {
        const url = URL.createObjectURL(new Blob([bytes], { type }));
        const link = Object.assign(document.createElement('a'), { href: url, download: name });
        document.body.appendChild(link);
        link.click();
        link.remove();
        setTimeout(() => URL.revokeObjectURL(url), 10_000);
        return `Downloads/${name}`;
      },
    },
    exports: {
      /** The backend saves the table at 9:30 with these factor settings. */
      saveSettings: (factorSettings) => json(post('/api/export/settings', { factorSettings }, 'PUT')),
      status: () => json(fetch('/api/export/status')),
    },
    /** The backend's 09:15–09:20 opening-window collector (Kite WebSocket). */
    opening: {
      /** Server-sent events: the latest scanner payload, then each update (≤ 1/s). Returns unsubscribe. */
      subscribe(onUpdate, onError = () => {}) {
        let events;
        const startup = setTimeout(() => {
          events = new EventSource('/api/opening/events');
          events.onmessage = (e) => { try { onUpdate(JSON.parse(e.data)); } catch { /* ignore a bad frame */ } };
          events.onerror = () => onError('Opening-window updates disconnected; reconnecting…');
        }, 0);
        return () => { clearTimeout(startup); events?.close(); };
      },
      stock: (symbol) => json(fetch(`/api/opening/stock/${encodeURIComponent(symbol)}`)),
      prepare: () => json(fetch('/api/opening/prepare', { method: 'POST' })),
      replay: (body) => json(post('/api/opening/replay', body)),
      /** Read-only Kite setup check: instruments, historical, quote, WebSocket. */
      selfTest: () => json(fetch('/api/opening/selftest', { method: 'POST' })),
      saveSettings: (body) => json(post('/api/opening/settings', body, 'PUT')),
    },
    /** The 09:20 decision and paper trading (milestone 2: PAPER only; LIVE is not available). */
    trading: {
      state: (ledger = 'day') => json(fetch(`/api/trading/state?ledger=${ledger}`)),
      decision: (symbol, ledger = 'day') => json(fetch(`/api/trading/decision/${encodeURIComponent(symbol)}?ledger=${ledger}`)),
      saveSettings: (body) => json(post('/api/trading/settings', body, 'PUT')),
      kill: (on, ledger = 'day') => json(post('/api/trading/kill', { on, ledger })),
      closeAll: (ledger = 'day') => json(post('/api/trading/close-all', { ledger })),
      logUrl: (date) => `/api/trading/log/${date}`,
      /** 9:15 gap entries (paper): the list, one stock's plan now, and the report by gap type. */
      gapList: () => json(fetch('/api/trading/gap-list')),
      saveGapList: (body) => json(post('/api/trading/gap-list', body, 'PUT')),
      gapPlan: (symbol, side = 'BUY') => json(fetch(`/api/trading/gap-plan/${encodeURIComponent(symbol)}?side=${side}`)),
      gapReport: () => json(fetch('/api/trading/gap-report')),
      gapReportXlsxUrl: () => '/api/trading/gap-report?format=xlsx',
    },
    /** Live prices from NSE (fallback when Kite has no market data), in Kite's quote shape. */
    live: { quote: (instruments) => json(post('/api/nse/live', { instruments })) },
    /** Time-triggered orders, sent by the backend (the browser can be closed). */
    scheduledOrders: {
      runsInBackground: true,
      list: () => json(fetch('/api/orders/scheduled')),
      add: (order) => json(post('/api/orders/scheduled', { order })),
      cancel: (id) => json(fetch(`/api/orders/scheduled/${encodeURIComponent(id)}`, { method: 'DELETE' })),
      /** Read Kite's record of a placed order (received, at the exchange, fills). */
      refreshKite: (id) => json(post(`/api/orders/scheduled/${encodeURIComponent(id)}/kite`, {})),
      /** Hand the Kite session to the backend (memory only); null clears it. */
      setSession: (s) => json(post('/api/orders/session', s ?? {}, 'PUT')),
    },
    confirm: {
      /** Saved 9:20 reading for a date, or null. */
      get: async (date) => (await json(fetch(`/api/confirm/${encodeURIComponent(date)}`))).reading ?? null,
      save: (reading) => json(post('/api/confirm', reading, 'PUT')),
    },
    reportCard: {
      status: () => json(fetch('/api/report-card/status')),
      get: (factorSettings) => json(post('/api/report-card', { factorSettings })),
    },
    /** AI Analyst (read-only research on the backend; the provider key stays there). */
    ai: {
      status: () => json(fetch('/api/ai/status')),
      snapshots: () => json(fetch('/api/ai/snapshots')),
      /** Errors carry `code` (e.g. 'stale', 'quiet', 'not_configured'); `signal` cancels. */
      async ask(body, signal) {
        const response = await fetch('/api/ai/ask', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body), signal });
        const payload = await response.json().catch(() => ({}));
        if (!response.ok) throw Object.assign(new Error(payload.error || `Request failed (HTTP ${response.status}).`), { code: payload.code ?? null });
        return payload;
      },
      source: (chunkId) => json(fetch(`/api/ai/source/${encodeURIComponent(chunkId)}`)),
      index: (embed) => json(post('/api/ai/index', { embed })),
      cancelIndex: () => json(post('/api/ai/index/cancel', {})),
    },
    kite: {
      createSession: async (body) => (await json(post('/api/kite/session', body))).session,
      positions: async (body) => {
        const { positions } = await json(post('/api/kite/positions', body));
        return Array.isArray(positions) ? positions : [];
      },
      accountSummary: async (body) => (await json(post('/api/kite/account-summary', body))).account ?? null,
      placeOrder: async (body) => (await json(post('/api/kite/order', body))).order,
      /** { "NSE:SYMBOL": quote } for the given instruments. */
      quote: async (body) => (await json(post('/api/kite/quote', body))).quotes ?? {},
    },
  };
}
